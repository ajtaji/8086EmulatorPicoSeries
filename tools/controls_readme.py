"""Write the "Controls" table of README.md and desktop/README.md from desktop/controls.pbi,
the one table the desktop window's keyboard code and its Controls tab read.

  py -3 tools/controls_readme.py          rewrites the section between the two markers
  py -3 tools/controls_readme.py --check  exits 1 if a README is not what the table gives
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- controls: generated by tools/controls_readme.py from desktop/controls.pbi -->'
END = '<!-- end of controls -->'


def rows():
    text = (ROOT / 'desktop' / 'controls.pbi').read_text(encoding='utf-8')
    body = text[text.index('CtlTable:'):text.index('EndDataSection')]
    # a row: Data.l group, when, key, value [: or newline] Data.s "keys", "what"
    pat = re.compile(r'Data\.l (#CTL_\w+), #CTL_\w+, [^,]+, [^\n:]+?\s*(?::|\n)\s*Data\.s "([^"]*)", "([^"]*)"')
    return [(g, k, w) for g, k, w in pat.findall(body)]


def table():
    out = [BEGIN, '']
    group = None
    for g, keys, what in rows():
        if g != group:
            group = g
            if g == '#CTL_PC':
                out += ["**The PC's keyboard** - on the PC screen tab, or in full screen, while the PC runs:", '',
                        '| Key | Sends |', '|---|---|']
            else:
                out += ['', '**The window:**', '', '| Key | Does |', '|---|---|']
        out.append(f'| {keys} | {what} |')
    out += ['', END]
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    new = table()
    bad = 0
    for path in (ROOT / 'README.md', ROOT / 'desktop' / 'README.md'):
        text = path.read_text(encoding='utf-8')
        if BEGIN not in text:
            print(f'{path.name}: no controls section markers')
            bad = 1
            continue
        s = text.index(BEGIN)
        e = text.index(END) + len(END)
        updated = text[:s] + new + text[e:]
        if updated != text:
            if check:
                print(f'{path.relative_to(ROOT)}: Controls section is out of date')
                bad = 1
            else:
                path.write_text(updated, encoding='utf-8', newline='\n')
                print(f'{path.relative_to(ROOT)}: Controls section written')
    n = len(rows())
    print(f'{n} rows in desktop/controls.pbi')
    sys.exit(bad)


if __name__ == '__main__':
    main()
