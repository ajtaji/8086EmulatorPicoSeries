"""Write the example .COM programs for the desktop program (desktop/examples/).

Hand-encoded 8086 with label fix-ups (no assembler needed). They use the
desktop machine's INT 21h services (AH=02h, 09h, 4Ch).

  hello.com   prints a line and exits
  sieve.com   counts the primes below 10000 with a byte sieve and prints 1229
"""
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'desktop' / 'examples'

class Asm:
    def __init__(self, org=0x100):
        self.org, self.b, self.labels, self.fix = org, bytearray(), {}, []
    def here(self):
        return self.org + len(self.b)
    def label(self, name):
        self.labels[name] = self.here()
    def emit(self, *bs):
        self.b += bytes(bs)
    def w(self, v):
        self.b += struct.pack('<H', v & 0xFFFF)
    def wl(self, name):            # absolute 16-bit address of a label
        self.fix.append(('abs', len(self.b), name)); self.b += b'\0\0'
    def jr(self, opcode, name):    # short jump / Jcc / LOOP to a label
        self.emit(opcode); self.fix.append(('rel', len(self.b), name)); self.b += b'\0'
    def done(self):
        for kind, at, name in self.fix:
            t = self.labels[name]
            if kind == 'abs':
                self.b[at:at + 2] = struct.pack('<H', t)
            else:
                d = t - (self.org + at + 1)
                assert -128 <= d <= 127, (name, d)
                self.b[at] = d & 0xFF
        return bytes(self.b)

def hello():
    a = Asm()
    a.emit(0xBA); a.wl('msg')            # mov dx, msg
    a.emit(0xB4, 0x09, 0xCD, 0x21)       # mov ah, 9 / int 21h
    a.emit(0xB8); a.w(0x4C00)            # mov ax, 4C00h
    a.emit(0xCD, 0x21)                   # int 21h
    a.label('msg'); a.b += b'Hello from the 8086 core.\n$'
    return a.done()

def sieve():
    N, FLAGS = 10000, 0x2000
    a = Asm()
    a.emit(0xBF); a.w(FLAGS)             # mov di, flags
    a.emit(0xB9); a.w(N)                 # mov cx, N
    a.emit(0xB0, 0x01, 0xFC, 0xF3, 0xAA) # mov al, 1 / cld / rep stosb
    a.emit(0xBB); a.w(2)                 # mov bx, 2
    a.label('outer')
    a.emit(0x89, 0xD8)                   # mov ax, bx
    a.emit(0xF7, 0xE3)                   # mul bx
    a.emit(0x3D); a.w(N)                 # cmp ax, N
    a.jr(0x73, 'count')                  # jae count
    a.emit(0x80, 0xBF); a.w(FLAGS); a.emit(0x00)   # cmp byte [bx+flags], 0
    a.jr(0x74, 'next')                   # je next
    a.emit(0x89, 0xC6)                   # mov si, ax
    a.label('mark')
    a.emit(0xC6, 0x84); a.w(FLAGS); a.emit(0x00)   # mov byte [si+flags], 0
    a.emit(0x01, 0xDE)                   # add si, bx
    a.emit(0x81, 0xFE); a.w(N)           # cmp si, N
    a.jr(0x72, 'mark')                   # jb mark
    a.label('next')
    a.emit(0x43)                         # inc bx
    a.jr(0xEB, 'outer')                  # jmp outer
    a.label('count')
    a.emit(0x31, 0xD2)                   # xor dx, dx
    a.emit(0xBE); a.w(2)                 # mov si, 2
    a.label('cnt')
    a.emit(0x80, 0xBC); a.w(FLAGS); a.emit(0x00)   # cmp byte [si+flags], 0
    a.jr(0x74, 'skip')                   # je skip
    a.emit(0x42)                         # inc dx
    a.label('skip')
    a.emit(0x46)                         # inc si
    a.emit(0x81, 0xFE); a.w(N)           # cmp si, N
    a.jr(0x72, 'cnt')                    # jb cnt
    a.emit(0x52)                         # push dx
    a.emit(0xBA); a.wl('msg')            # mov dx, msg
    a.emit(0xB4, 0x09, 0xCD, 0x21)       # mov ah, 9 / int 21h
    a.emit(0x58)                         # pop ax
    a.emit(0xBB); a.w(10)                # mov bx, 10
    a.emit(0x31, 0xC9)                   # xor cx, cx
    a.label('div')
    a.emit(0x31, 0xD2)                   # xor dx, dx
    a.emit(0xF7, 0xF3)                   # div bx
    a.emit(0x52, 0x41)                   # push dx / inc cx
    a.emit(0x09, 0xC0)                   # or ax, ax
    a.jr(0x75, 'div')                    # jnz div
    a.label('pr')
    a.emit(0x5A)                         # pop dx
    a.emit(0x80, 0xC2, 0x30)             # add dl, '0'
    a.emit(0xB4, 0x02, 0xCD, 0x21)       # mov ah, 2 / int 21h
    a.jr(0xE2, 'pr')                     # loop pr
    a.emit(0xB2, 0x0A, 0xB4, 0x02, 0xCD, 0x21)     # newline
    a.emit(0xB8); a.w(0x4C00)            # mov ax, 4C00h
    a.emit(0xCD, 0x21)                   # int 21h
    a.label('msg'); a.b += b'primes below 10000: $'
    return a.done()

OUT.mkdir(parents=True, exist_ok=True)
lines = ['; Generated by tools/make_examples.py: the example .COM programs as data,',
         '; for the Pico demo (the desktop program loads desktop/examples/*.com).',
         'DataSection']
for name, label, fn in (('hello.com', 'HelloCom', hello), ('sieve.com', 'SieveCom', sieve)):
    data = fn()
    (OUT / name).write_bytes(data)
    print(name, len(data), 'bytes:', data.hex())
    lines.append(f'  {label}:')
    for i in range(0, len(data), 16):
        lines.append('  Data.a ' + ','.join(f'${v:02X}' for v in data[i:i + 16]))
    lines.append(f'  {label}End:')
lines.append('EndDataSection')
(ROOT / 'src' / 'examples.pmi').write_text(chr(10).join(lines) + chr(10), newline=chr(10))
