"""Write src/cgafont.pmi: an 8x8 character set in code-page-437 order for the PC
machine's CGA text modes. No IBM ROM is used: the glyphs come from Daniel Hepper's
public-domain font8x8 (Diagnostics/upstream/font8x8, commit 8e279d2d), arranged
into CP437 positions: printable ASCII, the box-drawing set (179-218), the shades
and blocks (176-178, 219-223) and a small square (254). Codes 0-31, 127 and the
accented/Greek range (128-175, 224-253) are blank.

Each glyph is 8 bytes, top row first, MSB = leftmost pixel (as CGA shifts them).
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
UP = ROOT / 'Diagnostics' / 'upstream' / 'font8x8'

def load(name):
    text = (UP / name).read_text()
    rows = re.findall(r'\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}', text)
    return [[int(v, 16) for v in r.split(',')] for r in rows]

basic, box, block = load('font8x8_basic.h'), load('font8x8_box.h'), load('font8x8_block.h')
assert len(basic) == 128 and len(box) == 128 and len(block) >= 32, (len(basic), len(box), len(block))

def rev(b):
    return int(f'{b:08b}'[::-1], 2)

glyph = [[0] * 8 for _ in range(256)]
for c in range(32, 127):
    glyph[c] = [rev(b) for b in basic[c]]
BOX = {179: 0x02, 180: 0x24, 181: 0x61, 182: 0x62, 183: 0x56, 184: 0x55, 185: 0x63, 186: 0x51, 187: 0x57,
       188: 0x5D, 189: 0x5C, 190: 0x5B, 191: 0x10, 192: 0x14, 193: 0x34, 194: 0x2C, 195: 0x1C, 196: 0x00,
       197: 0x3C, 198: 0x5E, 199: 0x5F, 200: 0x5A, 201: 0x54, 202: 0x69, 203: 0x66, 204: 0x60, 205: 0x50,
       206: 0x6C, 207: 0x67, 208: 0x68, 209: 0x64, 210: 0x65, 211: 0x59, 212: 0x58, 213: 0x52, 214: 0x53,
       215: 0x6B, 216: 0x6A, 217: 0x18, 218: 0x0C}
for c, u in BOX.items():
    glyph[c] = [rev(b) for b in box[u]]
BLOCK = {176: 0x11, 177: 0x12, 178: 0x13, 219: 0x08, 220: 0x04, 221: 0x0C, 222: 0x10, 223: 0x00}
for c, u in BLOCK.items():
    glyph[c] = [rev(b) for b in block[u]]
glyph[254] = [0x00, 0x00, 0x3C, 0x3C, 0x3C, 0x3C, 0x00, 0x00]

lines = ['; Generated by tools/make_cgafont.py: the PC machine\'s 8x8 CGA character set, CP437 order.',
         '; Glyphs from font8x8 by Daniel Hepper (public domain); 8 bytes a glyph, MSB = leftmost pixel.',
         'DataSection', '  CgaFont:']
for c in range(256):
    lines.append('  Data.a ' + ','.join(f'${v:02X}' for v in glyph[c]) + f'   ; {c}')
lines.append('EndDataSection')
(ROOT / 'src' / 'cgafont.pmi').write_text('\n'.join(lines) + '\n', newline='\n')
print('cgafont.pmi: 256 glyphs')
