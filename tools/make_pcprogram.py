"""Write src/pcprogram.pmi: the .COM the Pico PC machine (src/pc.picow) runs.

  py -3 tools/make_pcprogram.py [file.com [out.pmi]]   (default desktop/examples/bars.com -> src/pcprogram.pmi)

The bytes go in a DataSection with their exact length as #PC_PROGRAM_BYTES
(on the Picos ?End - ?Start of a DataSection is rounded up to 4).
"""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'desktop' / 'examples' / 'bars.com'
data = src.read_bytes()
if len(data) > 0x9F900:
    raise SystemExit(f'{src} is {len(data)} bytes: more than fits from 0050:0100')
lines = [f'; Generated by tools/make_pcprogram.py from {src.name}: the program the Pico PC machine runs.',
         f'#PC_PROGRAM_BYTES = {len(data)}',
         'DataSection', '  PcProgram:']
for i in range(0, len(data), 16):
    lines.append('  Data.a ' + ','.join(f'${v:02X}' for v in data[i:i + 16]))
lines.append('EndDataSection')
out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'src' / 'pcprogram.pmi'
out.write_text('\n'.join(lines) + '\n', newline='\n')
print(f'{out.name}: {src.name}, {len(data)} bytes')
